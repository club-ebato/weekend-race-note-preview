// c：app.js の部品（routeBack, innerHero, bar, btn）
export function legalPage(kind, c) {
  const p = pages[kind] || pages.terms;
  const body = p.rows
    ? `<dl class="lg-table">${p.rows.map(([k, v]) => `<div><dt>${k}</dt><dd>${v}</dd></div>`).join('')}</dl>`
    : p.sections.map(([h, items], i) => `${c.bar(h, String(i + 1))}<ul class="lg-list">${items.map(t => `<li>${t}</li>`).join('')}</ul>`).join('');
  return `<div class="content inner-page lg-page">${c.routeBack('about', 'このサイトについてに戻る')}${c.innerHero(service, p.title, p.lead, 'guide')}${draft}${body}<p class="lg-date">下書き作成日：2026年11月17日</p>${legalLinks(kind)}${c.btn('ホームへ戻る', 'home', 'secondary')}</div>`;
}

// 他の2ページへの入口。current を渡すと、いま開いているページは出さない。
export function legalLinks(current = '') {
  return `<nav class="lg-links" aria-label="規約・運営会社">${legalKinds.filter(k => k !== current).map(k => `<button data-go="${k}">${pages[k].title}</button>`).join('')}</nav>`;
}

