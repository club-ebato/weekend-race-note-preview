export function horseInsight(race,horse){
  if(race?.draw?.source!=='sample'||!sampleDraws[race.id]||!Number.isInteger(horse)) return null;
  if(horse===5 && race.free) return null;
  const copy=insights[characterFor(race).id]?.[horse];
  return copy?{...copy,sample:true}:null;
}
